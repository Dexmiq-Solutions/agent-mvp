"""BRD Rewriter Sub-Agent implementation.

Provides the dedicated, specialized document correction execution capability
for the BRD Agent architecture. Executes targeted document modifications strictly
as specified by the Final Validation Sub-Agent with minimum necessary document change.

Strict Architectural Boundaries:
- Final Validation owns diagnosis (what is wrong, where it is, and why).
- BRD Rewriter owns execution (applying the specified correction minimally).
- Rewriter has NO tools (tools=[]: cannot call RAG, access databases, or invoke external tools).
- Rewriter does not independently search, reinterpret, or reassess project evidence.
- Rewriter modifies only the content specified by findings, preserving all untouched text.
- Rewriter never returns to Section Validation or re-evaluates section-level gates.
"""

